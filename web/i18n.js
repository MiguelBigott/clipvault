let idiomaActual = "es";

function t(clave, datos = {}) {
  const texto = TEXTOS[idiomaActual]?.[clave] ?? TEXTOS.es[clave] ?? clave;
  return texto.replace(/\{(\w+)\}/g, (_, k) => (datos[k] ?? `{${k}}`));
}

// tm muestra un Mensaje de la app ({clave, datos, causa}); la causa va traducida dentro.
function tm(m) {
  if (!m) return "";
  if (typeof m === "string") return m;
  return t(m.clave, { ...(m.datos || {}), causa: tm(m.causa) });
}

const localeActual = () => IDIOMAS[idiomaActual] || "es-ES";

// aplicarIdioma traduce los textos fijos del HTML: data-t (texto), data-t-aria, data-t-title
// y data-t-placeholder.
function aplicarIdioma(idioma) {
  idiomaActual = TEXTOS[idioma] ? idioma : "es";
  document.documentElement.lang = idiomaActual;
  document.querySelectorAll("[data-t]").forEach((n) => { n.textContent = t(n.dataset.t); });
  for (const [attr, nombre] of [["tAria", "aria-label"], ["tTitle", "title"], ["tPlaceholder", "placeholder"]]) {
    const sel = `[data-${attr.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}]`;
    document.querySelectorAll(sel).forEach((n) => n.setAttribute(nombre, t(n.dataset[attr])));
  }
}
